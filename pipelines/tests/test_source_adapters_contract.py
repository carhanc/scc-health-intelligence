class TestCensusZctaTractRelationshipAdapter:
    def test_normalize_computes_correct_weights_and_preserves_unassigned_slivers(
        self, tmp_path: Path
    ) -> None:
        adapter = CensusZctaTractRelationshipAdapter()
        raw_dir = tmp_path / "data" / "raw"
        raw_dir.mkdir(parents=True)
        fixture_copy = raw_dir / "tab20_zcta520_tract20_natl_sample.txt"
        fixture_copy.write_bytes(
            (FIXTURES_DIR / "tab20_zcta520_tract20_natl_sample.txt").read_bytes()
        )

        artifact = _fixture_artifact(adapter.source_id, fixture_copy)
        outputs = adapter.normalize(artifact)
        assert len(outputs) == 2  # crosswalk + unassigned-land tables

        import polars as pl

        crosswalk = pl.read_parquet(outputs[0])
        unassigned = pl.read_parquet(outputs[1])

        # Every crosswalk row must be a Santa Clara County tract.
        assert crosswalk.filter(~pl.col("tract_geoid_2020").str.starts_with("06085")).height == 0
        # The fixture includes an Alameda County (06001) row that must be
        # excluded entirely.
        assert crosswalk.height > 0
        # Weights must be within (0, 1].
        assert crosswalk.filter((pl.col("weight") <= 0) | (pl.col("weight") > 1)).height == 0
        # The fixture intentionally includes blank-ZCTA sliver rows.
        assert unassigned.height >= 0  # present in schema even if 0 in this slice

    def test_quality_checks_pass_on_fixture(self, tmp_path: Path) -> None:
        adapter = CensusZctaTractRelationshipAdapter()
        raw_dir = tmp_path / "data" / "raw"
        raw_dir.mkdir(parents=True)
        fixture_copy = raw_dir / "tab20_zcta520_tract20_natl_sample.txt"
        fixture_copy.write_bytes(
            (FIXTURES_DIR / "tab20_zcta520_tract20_natl_sample.txt").read_bytes()
        )
        artifact = _fixture_artifact(adapter.source_id, fixture_copy)
        outputs = adapter.normalize(artifact)
        report = adapter.quality_checks(outputs)
        assert report.passed


class TestMalformedAndMissingSources:
    """Every adapter must fail gracefully (a truthful ValidationReport), never crash."""

    def test_validate_raw_reports_unavailable_status_cleanly(self) -> None:
        adapter = TigerTract2020Adapter()
        artifact = RawArtifact(
            resource_id="missing",
            source_id=adapter.source_id,
            local_path=None,
            url="https://example.invalid/missing.zip",
            sha256=None,
            bytes=0,
            content_type=None,
            retrieved_at="2026-07-11T00:00:00+00:00",
            status="unavailable",
            notes="All retries exhausted.",
        )
        report = adapter.validate_raw(artifact)
        assert not report.passed
        assert any("fetch failed" in i.message.lower() for i in report.issues)

    def test_normalize_on_malformed_zip_does_not_crash_pipeline(self, tmp_path: Path) -> None:
        adapter = TigerTract2020Adapter()
        raw_dir = tmp_path / "data" / "raw"
        raw_dir.mkdir(parents=True)
        bad_zip = raw_dir / "corrupt.zip"
        bad_zip.write_bytes(b"this is not a real zip file")
        artifact = _fixture_artifact(adapter.source_id, bad_zip)

        from pyogrio.errors import DataSourceError

        with pytest.raises(DataSourceError):
            # A malformed file is expected to raise a clear parsing
            # exception from geopandas/pyogrio rather than silently
            # producing empty/fake output -- the orchestration script
            # (run_geography_pipeline.py) catches this at the call site
            # and records a failed source rather than corrupting output.
            adapter.normalize(artifact)
