from scc_health_pipeline.sources.tiger_place import TigerPlace2020Adapter
from scc_health_pipeline.sources.tiger_tract import TigerTract2020Adapter

FIXTURES_DIR = Path(__file__).resolve().parents[1] / "fixtures"


def _fixture_artifact(source_id: str, local_path: Path) -> RawArtifact:
    return RawArtifact(
        resource_id="fixture",
        source_id=source_id,
        local_path=local_path,
        url="file://fixture",
        sha256="fixture",
        bytes=local_path.stat().st_size,
        content_type="fixture",
        retrieved_at="2026-07-11T00:00:00+00:00",
        status="success",
    )


class TestTigerTractAdapter:
    def test_normalize_filters_to_santa_clara_county_only(self, tmp_path: Path) -> None:
        adapter = TigerTract2020Adapter()
        # normalize() derives staged_dir from local_path.parents[1]/"staged",
        # so the fixture must live under a fake "raw" directory for that
        # relative path math to land in a temp location during the test.
        raw_dir = tmp_path / "data" / "raw"
        raw_dir.mkdir(parents=True)
        fixture_copy = raw_dir / "tl_2020_06_tract_sample.zip"
        fixture_copy.write_bytes((FIXTURES_DIR / "tl_2020_06_tract_sample.zip").read_bytes())

        artifact = _fixture_artifact(adapter.source_id, fixture_copy)
        outputs = adapter.normalize(artifact)
        assert len(outputs) == 1

        import geopandas as gpd

        gdf = gpd.read_parquet(outputs[0])
        # Fixture intentionally includes 1 non-Santa-Clara row to prove the
        # county filter actually removes it.
        assert (gdf["county_fips"] == "085").all()
        assert len(gdf) >= 1
        assert (gdf["tract_geoid_2020"].str.len() == 11).all()

    def test_quality_checks_flag_duplicate_geoids(self, tmp_path: Path) -> None:
        adapter = TigerTract2020Adapter()
        import geopandas as gpd
        from shapely.geometry import Point

        gdf = gpd.GeoDataFrame(
            {
                "tract_geoid_2020": ["06085500100", "06085500100"],
                "geometry": [Point(-121.9, 37.3), Point(-121.9, 37.3)],
            },
            crs="EPSG:4326",
        )
        out_path = tmp_path / "dup_tracts.parquet"
        gdf.to_parquet(out_path)
        report = adapter.quality_checks([out_path])
        assert not report.passed
        assert any("duplicate" in i.message.lower() for i in report.issues)


